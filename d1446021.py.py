def calculate_expenses(raw_cost_str, raw_people_str, discount):
    # 1. 資料清理與型別轉換：移除貨幣符號、逗號與空白
    cost_clean = raw_cost_str.replace('NT$', '').replace('$', '').replace(',', '').strip()
    original_cost = float(cost_clean)

    # 萃取人數中的數字字元
    people_clean = ''.join(filter(str.isdigit, raw_people_str))
    people_count = int(people_clean)

    # 2. 計算邏輯
    service_fee = original_cost * 0.10             # 10% 服務費
    total_amount = original_cost + service_fee - discount # 應付總金額
    per_person = total_amount / people_count       # 每人分攤費用

    # 3. 預算判斷 (每人預算 300 元)
    budget = 300.0
    is_over_budget = per_person > budget

    return {
        "original_cost": original_cost,
        "service_fee": service_fee,
        "discount": discount,
        "total_amount": total_amount,
        "people_count": people_count,
        "per_person": per_person,
        "is_over_budget": is_over_budget
    }

# 三組測試案例資料
test_cases = [
    {"cost": "$1,500", "people": "5 人", "discount": 100},
    {"cost": "NT$ 2,400", "people": "8", "discount": 200},
    {"cost": "$1,200", "people": "6 人", "discount": 300}
]

# 執行測試與輸出結果摘要
for i, tc in enumerate(test_cases, 1):
    res = calculate_expenses(tc["cost"], tc["people"], tc["discount"])
    print(f"=== 測試案例 {i} ===")
    print(f"原始餐費文字: {tc['cost']} -> 數值: {res['original_cost']} 元")
    print(f"人數文字: {tc['people']} -> 數值: {res['people_count']} 人")
    print(f"折價券金額: {tc['discount']} 元")
    print(f"10% 服務費: {res['service_fee']} 元")
    print(f"應付總金額: {res['total_amount']} 元")
    print(f"每人分攤費用: {res['per_person']:.2f} 元")
    print(f"是否超過 300 元預算: {'⚠️ 超過預算' in ('⚠️ 超過預算' if res['is_over_budget'] else '✅ 未超過') or ('超過' if res['is_over_budget'] else '未超過')}\n")